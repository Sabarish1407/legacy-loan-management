-- V1__init_schema.sql: Initial schema for Legacy Loan Management System

CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    phone VARCHAR(30) NOT NULL,
    national_id VARCHAR(50) NOT NULL UNIQUE,
    address VARCHAR(255) NOT NULL,
    date_of_birth DATE NOT NULL,
    monthly_income NUMERIC(15, 2) NOT NULL,
    employment_type VARCHAR(50) NOT NULL,
    credit_score INT DEFAULT 700,
    kyc_status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(50) NOT NULL,
    customer_id BIGINT,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_users_customer FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE SET NULL
);

CREATE TABLE loan_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    loan_type VARCHAR(30) NOT NULL,
    requested_amount NUMERIC(15, 2) NOT NULL,
    interest_rate NUMERIC(5, 2) NOT NULL,
    tenure_months INT NOT NULL,
    employment_type VARCHAR(50) NOT NULL,
    monthly_income NUMERIC(15, 2) NOT NULL,
    application_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(30) NOT NULL DEFAULT 'SUBMITTED',
    rejection_reason VARCHAR(500),
    approved_amount NUMERIC(15, 2),
    approved_tenure_months INT,
    approved_interest_rate NUMERIC(5, 2),
    review_notes VARCHAR(1000),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_loan_app_customer FOREIGN KEY (customer_id) REFERENCES customers(id)
);

CREATE TABLE loan_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL,
    account_number VARCHAR(50) NOT NULL UNIQUE,
    principal_amount NUMERIC(15, 2) NOT NULL,
    annual_interest_rate NUMERIC(5, 2) NOT NULL,
    tenure_months INT NOT NULL,
    monthly_emi NUMERIC(15, 2) NOT NULL,
    outstanding_principal NUMERIC(15, 2) NOT NULL,
    disbursement_date TIMESTAMP NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    closed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_loan_acc_app FOREIGN KEY (application_id) REFERENCES loan_applications(id),
    CONSTRAINT fk_loan_acc_customer FOREIGN KEY (customer_id) REFERENCES customers(id)
);

CREATE TABLE disbursements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL UNIQUE,
    loan_account_id BIGINT NOT NULL UNIQUE,
    amount NUMERIC(15, 2) NOT NULL,
    disbursement_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    account_number VARCHAR(50) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'SUCCESS',
    reference_number VARCHAR(100) NOT NULL UNIQUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_disb_app FOREIGN KEY (application_id) REFERENCES loan_applications(id),
    CONSTRAINT fk_disb_account FOREIGN KEY (loan_account_id) REFERENCES loan_accounts(id)
);

CREATE TABLE repayment_schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_account_id BIGINT NOT NULL,
    installment_number INT NOT NULL,
    due_date DATE NOT NULL,
    principal_amount NUMERIC(15, 2) NOT NULL,
    interest_amount NUMERIC(15, 2) NOT NULL,
    total_emi NUMERIC(15, 2) NOT NULL,
    outstanding_principal NUMERIC(15, 2) NOT NULL,
    paid_amount NUMERIC(15, 2) NOT NULL DEFAULT 0.00,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    paid_date DATE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_sched_account FOREIGN KEY (loan_account_id) REFERENCES loan_accounts(id),
    CONSTRAINT uk_sched_acc_inst UNIQUE (loan_account_id, installment_number)
);

CREATE TABLE loan_repayments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_account_id BIGINT NOT NULL,
    payment_reference VARCHAR(100) NOT NULL UNIQUE,
    idempotency_key VARCHAR(100) NOT NULL UNIQUE,
    amount NUMERIC(15, 2) NOT NULL,
    payment_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    payment_method VARCHAR(50) NOT NULL DEFAULT 'SIMULATED_GATEWAY',
    principal_component NUMERIC(15, 2) NOT NULL DEFAULT 0.00,
    interest_component NUMERIC(15, 2) NOT NULL DEFAULT 0.00,
    late_fee NUMERIC(15, 2) NOT NULL DEFAULT 0.00,
    status VARCHAR(30) NOT NULL DEFAULT 'SUCCESS',
    notes VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_repay_account FOREIGN KEY (loan_account_id) REFERENCES loan_accounts(id)
);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_name VARCHAR(100) NOT NULL,
    entity_id VARCHAR(100) NOT NULL,
    action VARCHAR(100) NOT NULL,
    performed_by VARCHAR(100) NOT NULL,
    timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    details VARCHAR(1000),
    client_ip VARCHAR(50)
);

-- Indexes for performance and lookup
CREATE INDEX idx_customer_email ON customers(email);
CREATE INDEX idx_customer_national_id ON customers(national_id);
CREATE INDEX idx_loan_app_customer ON loan_applications(customer_id);
CREATE INDEX idx_loan_app_status ON loan_applications(status);
CREATE INDEX idx_loan_acc_customer ON loan_accounts(customer_id);
CREATE INDEX idx_loan_acc_number ON loan_accounts(account_number);
CREATE INDEX idx_sched_acc_status ON repayment_schedules(loan_account_id, status);
CREATE INDEX idx_repay_acc ON loan_repayments(loan_account_id);
CREATE INDEX idx_repay_idempotency ON loan_repayments(idempotency_key);
CREATE INDEX idx_audit_entity ON audit_logs(entity_name, entity_id);
